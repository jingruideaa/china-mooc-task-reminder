const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const ROOT = path.resolve(__dirname, '..');
function walk(dir) { return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => ['.git', '.local', 'node_modules'].includes(entry.name) ? [] : entry.isDirectory() ? walk(path.join(dir, entry.name)) : [path.join(dir, entry.name)]); }
let failed = false;
for (const file of walk(ROOT).filter(file => file.endsWith('.js'))) {
  const result = spawnSync(process.execPath, ['--check', file], { encoding: 'utf8', windowsHide: true });
  if (result.status !== 0) { failed = true; console.error(result.stderr); }
}
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'extension/manifest.json'), 'utf8'));
for (const file of [manifest.background.service_worker, manifest.action.default_popup, ...manifest.content_scripts.flatMap(item => item.js), ...Object.values(manifest.icons)]) {
  if (!fs.existsSync(path.join(ROOT, 'extension', file))) { failed = true; console.error('Missing extension asset: ' + file); }
}
const popup = fs.readFileSync(path.join(ROOT, 'extension', manifest.action.default_popup), 'utf8');
for (const [, file] of popup.matchAll(/(?:src|href)="([^":?#]+\.(?:js|css))"/g)) {
  if (!fs.existsSync(path.join(ROOT, 'extension', file))) { failed = true; console.error('Missing popup asset: ' + file); }
}
if (manifest.version !== require('../package.json').version) { failed = true; console.error('Package and extension versions differ.'); }
if (failed) process.exitCode = 1;
else console.log('JavaScript syntax, manifest and packaged assets verified. bridge_config.js is generated by setup.');
